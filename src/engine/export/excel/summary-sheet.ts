import ExcelJS from "exceljs";

import { REPORT_CONFIG } from "@/config/report";

import type { WorkbookPreview } from "@/types/preview";
import type { ClientWorkbookSummary } from "@/types/client";
import type { MatchingResult } from "@/types/matching";

import {
  styleWorksheet,
  styleTitleRow,
  styleSubtitleRow,
  styleTableHeader,
  styleTableRow,
} from "./styles";

export function buildSummarySheet(
  workbook: ExcelJS.Workbook,
  allocation: WorkbookPreview,
  client: ClientWorkbookSummary,
  result: MatchingResult
) {
  const worksheet =
    workbook.addWorksheet("Report Summary");

  styleWorksheet(worksheet);

  worksheet.getColumn(1).width = 28;
  worksheet.getColumn(2).width = 45;

  worksheet.mergeCells("A1:B1");

  const title =
    worksheet.getCell("A1");

  title.value =
    REPORT_CONFIG.title;

  styleTitleRow(
    worksheet.getRow(1)
  );

  worksheet.mergeCells("A3:B3");

  worksheet.getCell("A3").value =
    REPORT_CONFIG.organisation;

  styleSubtitleRow(
    worksheet.getRow(3)
  );

  worksheet.addRow([]);

  worksheet.addRow([
    "Report Information",
    "",
  ]);

  styleTableHeader(
    worksheet.lastRow!
  );

  worksheet.addRows([
    [
      "Allocation Dataset",
      allocation.fileName,
    ],
    [
      "Allocation Records",
      allocation.totalRecords,
    ],
    [
      "Client Records",
      client.totalRecords,
    ],
    [
      "Generated By",
      `${REPORT_CONFIG.productName} — a software tool by ${REPORT_CONFIG.author}`,
    ],
  ]);

  worksheet.addRow([]);

  worksheet.addRow([
    "Placement Summary",
    "",
  ]);

  styleTableHeader(
    worksheet.lastRow!
  );

  worksheet.addRows([
    [
      "Total Client Records",
      result.totalClientRecords,
    ],
    [
      "Matched",
      result.matchedCount,
    ],
    [
      "Duplicate Matches",
      result.duplicateCount,
    ],
    [
      "Unmatched",
      result.unmatchedCount,
    ],
    [
      "Match Rate",
      `${result.matchRate}%`,
    ],
  ]);

  worksheet.eachRow((row, rowNumber) => {
    if (
      rowNumber !== 1 &&
      rowNumber !== 3
    ) {
      styleTableRow(row);
    }
  });

  worksheet.getColumn(1).width = 28;
  worksheet.getColumn(2).width = 45;
}